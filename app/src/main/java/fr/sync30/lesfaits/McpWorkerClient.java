/**
 * App-worker protocol already supported by CHK Universal Control v1.0.4.
 * It uses /api/onboard and /api/agent/{appId}/poll|result, not /oauth/register.
 * Pairing requires a short-lived invite authorized through the existing MCP.
 * The permanent worker secret is generated by the server and stored with Keystore.
 */
final class McpWorkerClient {
    static final String BASE="https://chk-universal-1.taild9e4de.ts.net";
    static final String MCP_URL=BASE+"/mcp";
    private static final String TAG="LesFaitsWorker";
    private static final int JOB_ID=43030;
    private static final long FIFTEEN_MIN=15L*60L*1000L;
    private static final ExecutorService pool=Executors.newSingleThreadExecutor();
    private static final AtomicBoolean polling=new AtomicBoolean(false);
    interface Listener{void done(boolean success,String message);}
    private McpWorkerClient(){}
    static boolean connected(SecurePrefs p){
        return !p.value("worker_id").isEmpty() && !p.protectedValue("worker_secret").isEmpty();
    }
    static boolean isEnabled(SecurePrefs p) {
        return connected(p)&&"true".equals(p.value("worker_enabled"));
    }
    static String appId(SecurePrefs p){return p.value("worker_id");}
    private static final String[][] ACTIONS={
        {"lesfaits_list","Consulter les signalements de LES FAITS","true"},
        {"lesfaits_detail","Lire un dossier et ses observations","true"},
        {"lesfaits_stats","Statistiques des problèmes récurrents","true"},
        {"lesfaits_create","Enregistrer un nouveau signalement dans LES FAITS","false"}
    };
    static void pair(Context context,String invite,Listener listener){
        if(invite==null||!invite.matches("chkinvite_[A-Za-z0-9_-]{20,150}")){
            listener.done(false,"Invitation invalide. Crée une nouvelle invitation avec ton MCP existant.");return;
        }
        pool.execute(()->{
            try {
                JSONObject body=new JSONObject();
                body.put("name","LES FAITS — SYNC 30");
                body.put("invite",invite);
                JSONArray capabilities=new JSONArray();
                for(String[] action:ACTIONS){
                    JSONObject v=new JSONObject();v.put("name",action[0]);v.put("description",action[1]);v.put("readOnly",Boolean.parseBoolean(action[2]));
                    capabilities.put(v);
                }
                body.put("capabilities",capabilities);
                JSONObject result=call("POST","/api/onboard",null,body);
                String id=result.getString("id"),secret=result.getString("secret");
                if(!id.matches("[a-zA-Z0-9_-]{10,80}")||!secret.matches("chkapp_[A-Za-z0-9_-]{30,150}"))
                    throw new Exception("Réponse d'association non reconnue.");
                SecurePrefs prefs=new SecurePrefs(context);
                prefs.protectedValue("worker_secret",secret);
                prefs.value("worker_id",id);
                prefs.value("worker_enabled","true");
                prefs.value("worker_write_enabled","true");
                startJob(context,prefs);
                finish(context,listener,true,"LES FAITS est associé à ton serveur MCP. Lecture et création de signalements autorisées (écriture soumise à approbation).");
            }catch(Exception e){
                Log.w(TAG,"Pairing failed: "+e.getClass().getSimpleName());
                finish(context,listener,false,"Association refusée : "+safeError(e));
            }
        });
    }
    private static void finish(Context ctx,Listener cb,boolean success,String message){
        new android.os.Handler(ctx.getMainLooper()).post(()->cb.done(success,message));
    }
    private static String safeError(Exception e){
        String s=e.getMessage();
        if(s!=null && s.startsWith("HTTP "))return s;
        return "réseau indisponible ou invitation expirée";
    }
    static void setEnabled(Context context,SecurePrefs prefs,boolean enabled){
        prefs.value("worker_enabled",enabled?"true":"false");
        if(enabled)startJob(context,prefs);else stopJob(context);
    }
    static void disconnect(Context context,SecurePrefs prefs){
        stopJob(context);
        prefs.value("worker_id","");
        prefs.value("worker_enabled","false");
        prefs.value("worker_write_enabled","false");
        try{prefs.protectedValue("worker_secret","");}catch(Exception ignored){}
    }
    static void startJob(Context context,SecurePrefs prefs){
        if(!isEnabled(prefs))return;
        JobScheduler scheduler=(JobScheduler)context.getSystemService(Context.JOB_SCHEDULER_SERVICE);
        if(scheduler==null)return;
        JobInfo info=new JobInfo.Builder(JOB_ID,new ComponentName(context,McpPollJob.class))
            .setRequiredNetworkType(JobInfo.NETWORK_TYPE_ANY)
            .setPersisted(true)
            .setPeriodic(FIFTEEN_MIN)
            .build();
        scheduler.schedule(info);
    }
    private static void stopJob(Context context){
        JobScheduler scheduler=(JobScheduler)context.getSystemService(Context.JOB_SCHEDULER_SERVICE);
        if(scheduler!=null)scheduler.cancel(JOB_ID);
    }
    static void check(Context context,Listener listener){
        if(!polling.compareAndSet(false,true)){
            if(listener!=null)finish(context,listener,false,"Vérification déjà en cours.");
            return;
        }
        pool.execute(()->{
            try {
                SecurePrefs prefs=new SecurePrefs(context);
                if(!isEnabled(prefs))throw new Exception("Application non associée ou partage désactivé.");
                String id=prefs.value("worker_id"),secret=prefs.protectedValue("worker_secret");
                JSONObject res=call("GET","/api/agent/"+id+"/poll",secret,null);
                JSONObject task=res.optJSONObject("task");
                if(task==null){
                    if(listener!=null)finish(context,listener,true,"Connexion MCP active. Aucune demande ChatGPT en attente.");
                    return;
                }
                String taskId=task.optString("id",""),action=task.optString("action","");
                JSONObject result=process(context,action,task.optJSONObject("args"),taskId);
                JSONObject response=new JSONObject();
                response.put("task_id",taskId);response.put("result",result);
                call("POST","/api/agent/"+id+"/result",secret,response);
                if(listener!=null)finish(context,listener,true,"Demande ChatGPT traitée : "+action);
            }catch(Exception e){
                Log.w(TAG,"Poll failed: "+e.getClass().getSimpleName());
                if(listener!=null)finish(context,listener,false,"MCP : "+safeError(e));
            }finally{polling.set(false);}
        });
    }
    private static JSONObject process(Context context,String action,JSONObject args,String taskId)throws Exception{
        Store store=new Store(context);
        try {
            JSONObject response=new JSONObject();response.put("ok",true);
            JSONArray data=new JSONArray();
            if("lesfaits_list".equals(action)){
                String space=args==null?"TOUT":args.optString("espace","TOUT");
                boolean recurrent=args!=null&&args.optBoolean("recurrent_uniquement",false);
                int limit=args==null?40:Math.max(1,Math.min(70,args.optInt("limite",40)));
                int total=0;
                for(Store.Incident i:store.all()){
                    if(!"TOUT".equals(space)&&!space.equals(i.space))continue;
                    if(recurrent&&!i.recurring)continue;
                    total++;
                    if(data.length()<limit)data.put(summary(i));
                }
                response.put("total",total);response.put("faits",data);
            }else if("lesfaits_detail".equals(action)){
                long id=args==null?-1:args.optLong("id",-1);
                Store.Incident i=store.get(id);
                if(i==null){response.put("ok",false);response.put("error","Dossier introuvable");}
                else{
                    JSONObject v=summary(i);
                    v.put("description",i.description.length()>25000?i.description.substring(0,25000):i.description);
                    JSONArray notes=new JSONArray();
                    for(Store.Note note:store.notes(i.id)){
                        JSONObject n=new JSONObject();n.put("date",note.at);
                        n.put("texte",note.text.length()>6000?note.text.substring(0,6000):note.text);
                        notes.put(n);
                        if(notes.length()>=30)break;
                    }
                    v.put("observations",notes);v.put("photos_stockees",store.photos(i.id).size());
                    response.put("fait",v);
                }
            }else if("lesfaits_create".equals(action)){
                if(args==null || !"true".equals(new SecurePrefs(context).value("worker_write_enabled"))){
                    response.put("ok",false);response.put("error","Écriture non autorisée : réassocier LES FAITS depuis Réglages.");
                }else{
                    String title=args.optString("titre","").trim();
                    String description=args.optString("description","").trim();
                    String location=args.optString("lieu","").trim();
                    if(title.length()<3||title.length()>180||description.length()<20||description.length()>25000||location.length()>200){
                        response.put("ok",false);response.put("error","Titre, description ou lieu invalide.");
                    }else{
                        Store.Incident incident=new Store.Incident();
                        incident.title=title;incident.description=description;incident.location=location;
                        incident.space="PERSONNEL".equals(args.optString("espace"))?"PERSONNEL":"TERRAIN";
                        String category=args.optString("categorie","Conditions de travail");
                        incident.category=category.length()>0&&category.length()<=80?category:"Conditions de travail";
                        String severity=args.optString("importance","Normale");
                        incident.severity="Critique".equals(severity)?"Critique":"Élevée".equals(severity)?"Élevée":"Normale";
                        incident.recurring=args.optBoolean("recurrent",false);
                        long when=args.optLong("date",System.currentTimeMillis());
                        long now=System.currentTimeMillis();
                        incident.occurred=when>946684800000L&&when<=now+86400000L?when:now;
                        long id=store.insertMcp(incident,taskId);
                        response.put("id",id);response.put("message","Signalement enregistré sur le téléphone.");
                    }
                }
            }else if("lesfaits_stats".equals(action)){
                List<Store.Incident> list=store.all();int recurring=0,pending=0,done=0;
                for(Store.Incident i:list){
                    if(i.recurring)recurring++;
                    if("Résolu".equals(i.status))done++;
                    if("En cours".equals(i.status)||"Signalé".equals(i.status))pending++;
                }
                response.put("total",list.size());response.put("recurrents",recurring);
                response.put("actifs",pending);response.put("resolus",done);
            }else {
                response.put("ok",false);response.put("error","Action non autorisée");
            }
            return response;
        }finally{store.close();}
    }
    private static JSONObject summary(Store.Incident item)throws Exception{
        JSONObject obj=new JSONObject();
        obj.put("id",item.id);obj.put("titre",item.title);
        obj.put("categorie",item.category);obj.put("espace",item.space);
        obj.put("lieu",item.location);obj.put("date",item.occurred);
        obj.put("statut",item.status);obj.put("importance",item.severity);
        obj.put("recurrent",item.recurring);
        String d=item.description;obj.put("resume",d.length()>1200?d.substring(0,1200):d);
        return obj;
    }
    private static JSONObject call(String method,String path,String bearer,JSONObject body)throws Exception{
        HttpsURLConnection connection=null;
        try {
            URL url=new URL(BASE+path);
            connection=(HttpsURLConnection)url.openConnection();
            connection.setRequestMethod(method);
            connection.setConnectTimeout(13000);connection.setReadTimeout(20000);
            connection.setRequestProperty("Accept","application/json");
            if(bearer!=null&&!bearer.isEmpty())connection.setRequestProperty("Authorization","Bearer "+bearer);
            if(body!=null){
                byte[] bytes=body.toString().getBytes(StandardCharsets.UTF_8);
                connection.setDoOutput(true);
                connection.setRequestProperty("Content-Type","application/json; charset=utf-8");
                connection.setFixedLengthStreamingMode(bytes.length);
                try(OutputStream out=connection.getOutputStream()){out.write(bytes);}
            }
            int status=connection.getResponseCode();
            if(status<200||status>=300)throw new Exception("HTTP "+status);
            try(InputStream in=connection.getInputStream();ByteArrayOutputStream out=new ByteArrayOutputStream()){
                byte[] buffer=new byte[4096];int total=0,n;
                while((n=in.read(buffer))!=-1){
                    total+=n;if(total>360000)throw new Exception("Réponse serveur trop volumineuse.");
                    out.write(buffer,0,n);
                }
                return new JSONObject(out.toString("UTF-8"));
            }
        }finally{if(connection!=null)connection.disconnect();}
    }
}
